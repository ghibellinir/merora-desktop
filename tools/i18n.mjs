// Přidá texty z jiného souboru (hlášky serveru, rozhovor), ať nejsou všechny tady.
export function addTexts(more) {
  for (const lang of Object.keys(TEXTS)) Object.assign(TEXTS[lang], more[lang] ?? {});
}

// Text v jazyce z nastavení (nebo lang). Chybějící anglický text spadne na český, ať nikdy není prázdno.
export function tr(key, vars = {}, lang = language()) {
  let s = TEXTS[lang]?.[key] ?? TEXTS.cs[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const locale = (lang = language()) => (lang === 'en' ? 'en-GB' : 'cs-CZ');
